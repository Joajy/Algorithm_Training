WITH MAXSIZE AS (
    SELECT MAX(SIZE_OF_COLONY)        AS SIZE
         , YEAR(DIFFERENTIATION_DATE) AS YEAR
      FROM ECOLI_DATA
     GROUP BY YEAR(DIFFERENTIATION_DATE)
)

SELECT YEAR(DIFFERENTIATION_DATE) AS YEAR
     , SIZE - SIZE_OF_COLONY AS YEAR_DEV
     , ID
  FROM ECOLI_DATA   A
     , MAXSIZE      B
 WHERE YEAR(DIFFERENTIATION_DATE) = B.YEAR
 ORDER BY YEAR(DIFFERENTIATION_DATE) ASC, YEAR_DEV ASC