SELECT A.AUTHOR_ID
     , AUTHOR_NAME
     , CATEGORY
     , SUM(SALES * PRICE) AS TOTAL_SALES
  FROM BOOK         A
     , AUTHOR       B
     , BOOK_SALES   C
 WHERE A.AUTHOR_ID  = B.AUTHOR_ID
   AND A.BOOK_ID    = C.BOOK_ID
   AND (YEAR(SALES_DATE) = 2022 AND MONTH(SALES_DATE) = 1)
 GROUP BY AUTHOR_ID, CATEGORY
 ORDER BY AUTHOR_ID, CATEGORY DESC