WITH ARRANGE AS (
    SELECT ID, FISH_TYPE, TIME,
           CASE WHEN LENGTH IS NULL THEN 10
                ELSE LENGTH END AS LENGTH
      FROM FISH_INFO
)

SELECT COUNT(*) AS FISH_COUNT
     , MAX(B.LENGTH) AS MAX_LENGTH
     , A.FISH_TYPE
  FROM FISH_INFO            A
     , ARRANGE              B
 WHERE A.ID = B.ID
   AND A.FISH_TYPE = B.FISH_TYPE
 GROUP BY A.FISH_TYPE
 HAVING AVG(B.LENGTH) >= 33
 ORDER BY A.FISH_TYPE 