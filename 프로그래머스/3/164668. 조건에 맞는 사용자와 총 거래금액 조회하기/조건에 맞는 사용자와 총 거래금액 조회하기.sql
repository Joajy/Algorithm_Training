WITH TOTAL AS (
    SELECT SUM(PRICE) AS PRICE
         , WRITER_ID
      FROM USED_GOODS_BOARD
    WHERE STATUS = 'DONE'
    GROUP BY WRITER_ID
   HAVING SUM(PRICE) >= 700000
)

SELECT USER_ID, NICKNAME, SUM(PRICE) AS TOTAL_SALES
  FROM TOTAL            A
     , USED_GOODS_USER  B
 WHERE A.WRITER_ID = B.USER_ID
 GROUP BY WRITER_ID
 ORDER BY TOTAL_SALES