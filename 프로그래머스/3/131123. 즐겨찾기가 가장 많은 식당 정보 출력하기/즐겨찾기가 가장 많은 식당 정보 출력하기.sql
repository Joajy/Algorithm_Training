WITH BEST AS (
    SELECT MAX(FAVORITES) AS FAVORITES
         , FOOD_TYPE
      FROM REST_INFO
     GROUP BY FOOD_TYPE
)

SELECT A.FOOD_TYPE, A.REST_ID, A.REST_NAME, A.FAVORITES
  FROM REST_INFO A
     , BEST B
 WHERE A.FOOD_TYPE = B.FOOD_TYPE
   AND A.FAVORITES = B.FAVORITES
 ORDER BY FOOD_TYPE DESC